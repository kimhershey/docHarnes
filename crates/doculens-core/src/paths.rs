//! Filesystem layout: global app-data directory and the per-workspace layout
//! (design §3.6). All workspace paths are derived from the workspace root so a
//! workspace stays relocatable.

use std::path::{Path, PathBuf};

use crate::version::{APP_NAME, WORKSPACE_DIR_NAME};

/// Environment variable that overrides the global app-data directory
/// (used by tests, CI and portable installs).
pub const APP_DATA_ENV: &str = "DOCULENS_APP_DATA";

/// `%LOCALAPPDATA%\DocuLens` on Windows, `~/.local/share/DocuLens` on Linux,
/// `~/Library/Application Support/DocuLens` on macOS.
pub fn app_data_dir() -> PathBuf {
    if let Some(p) = std::env::var_os(APP_DATA_ENV) {
        return PathBuf::from(p);
    }
    dirs::data_local_dir().unwrap_or_else(|| PathBuf::from(".")).join(APP_NAME)
}

/// Global, per-machine files under the app-data directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppPaths {
    pub root: PathBuf,
}

impl AppPaths {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }
    pub fn default_location() -> Self {
        Self::new(app_data_dir())
    }
    /// `settings.json` — single source of truth for the active workspace path,
    /// theme, language, tier/model pins (decision 14).
    pub fn settings_file(&self) -> PathBuf {
        self.root.join("settings.json")
    }
    /// llama-server router presets (regenerated by the app, absolute paths).
    pub fn presets_file(&self) -> PathBuf {
        self.root.join("presets.ini")
    }
    /// `engines/<version>/{cu121|cu129|vulkan|cpu}/`
    pub fn engines_dir(&self) -> PathBuf {
        self.root.join("engines")
    }
    pub fn tokenizers_dir(&self) -> PathBuf {
        self.root.join("tokenizers")
    }
    pub fn logs_dir(&self) -> PathBuf {
        self.root.join("logs")
    }
    /// Global (shared across workspaces) model store, used only when the user
    /// opts out of the default workspace-local storage.
    pub fn global_models_dir(&self) -> PathBuf {
        self.root.join("models")
    }
}

/// Per-workspace layout (design §3.6). Only the root is stored; everything
/// else is derived so the folder can be moved freely.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspacePaths {
    pub root: PathBuf,
}

impl WorkspacePaths {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }
    pub fn app_dir(&self) -> PathBuf {
        self.root.join(WORKSPACE_DIR_NAME)
    }
    pub fn manifest_file(&self) -> PathBuf {
        self.app_dir().join("workspace.json")
    }
    pub fn lock_file(&self) -> PathBuf {
        self.app_dir().join("lock")
    }
    pub fn db_file(&self) -> PathBuf {
        self.app_dir().join("workspace.db")
    }
    /// Drop-in model folders (design §3.3.5): `<id>/{*.gguf, mmproj*.gguf, model.json, LICENSE}`.
    pub fn models_dir(&self) -> PathBuf {
        self.app_dir().join("models")
    }
    pub fn presets_file(&self) -> PathBuf {
        self.app_dir().join("presets.ini")
    }
    pub fn cache_dir(&self) -> PathBuf {
        self.app_dir().join("cache")
    }
    pub fn page_cache_dir(&self) -> PathBuf {
        self.cache_dir().join("pages")
    }
    pub fn thumb_cache_dir(&self) -> PathBuf {
        self.cache_dir().join("thumbs")
    }
    pub fn extractions_dir(&self) -> PathBuf {
        self.app_dir().join("extractions")
    }
    pub fn index_dir(&self) -> PathBuf {
        self.app_dir().join("index")
    }
    pub fn journal_dir(&self) -> PathBuf {
        self.app_dir().join("journal")
    }
    pub fn snapshots_dir(&self) -> PathBuf {
        self.app_dir().join("snapshots")
    }
    pub fn trash_dir(&self) -> PathBuf {
        self.app_dir().join("trash")
    }
    pub fn jobs_dir(&self) -> PathBuf {
        self.app_dir().join("jobs")
    }
    pub fn logs_dir(&self) -> PathBuf {
        self.app_dir().join("logs")
    }
    pub fn engine_pid_file(&self) -> PathBuf {
        self.app_dir().join("engine.pid")
    }
    pub fn engine_key_file(&self) -> PathBuf {
        self.app_dir().join("engine.key")
    }
    /// Watched folder for automatic import.
    pub fn inbox_dir(&self) -> PathBuf {
        self.root.join("inbox")
    }
    /// Organised documents (rename/move templates apply here).
    pub fn documents_dir(&self) -> PathBuf {
        self.root.join("documents")
    }
    pub fn exports_dir(&self) -> PathBuf {
        self.root.join("exports")
    }

    /// Every directory that must exist for an initialised workspace.
    pub fn all_dirs(&self) -> Vec<PathBuf> {
        vec![
            self.app_dir(),
            self.models_dir(),
            self.page_cache_dir(),
            self.thumb_cache_dir(),
            self.extractions_dir(),
            self.index_dir(),
            self.journal_dir(),
            self.snapshots_dir(),
            self.trash_dir(),
            self.jobs_dir(),
            self.logs_dir(),
            self.inbox_dir(),
            self.documents_dir(),
            self.exports_dir(),
        ]
    }

    /// Path of `p` relative to the workspace root (DB stores relative paths only).
    pub fn relative(&self, p: &Path) -> Option<PathBuf> {
        p.strip_prefix(&self.root).ok().map(Path::to_path_buf)
    }
}

/// Normalise a user-supplied folder path: trims whitespace, strips a trailing
/// separator, expands a leading `~`.
pub fn normalize_user_path(input: &str) -> PathBuf {
    let trimmed = input.trim().trim_end_matches(['/', '\\']);
    if let Some(rest) = trimmed.strip_prefix('~') {
        if let Some(home) = dirs::home_dir() {
            return home.join(rest.trim_start_matches(['/', '\\']));
        }
    }
    PathBuf::from(trimmed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn workspace_layout_is_derived_from_root() {
        let ws = WorkspacePaths::new("/w");
        assert_eq!(ws.manifest_file(), PathBuf::from("/w/.doculens/workspace.json"));
        assert_eq!(ws.models_dir(), PathBuf::from("/w/.doculens/models"));
        assert_eq!(ws.inbox_dir(), PathBuf::from("/w/inbox"));
        assert_eq!(ws.all_dirs().len(), 14);
        assert_eq!(ws.relative(Path::new("/w/documents/a.pdf")), Some(PathBuf::from("documents/a.pdf")));
        assert_eq!(ws.relative(Path::new("/other/a.pdf")), None);
    }

    #[test]
    fn app_data_env_override() {
        // Keep the test hermetic: the override must win over the platform dir.
        let paths = AppPaths::new("/tmp/x");
        assert_eq!(paths.settings_file(), PathBuf::from("/tmp/x/settings.json"));
        assert!(paths.engines_dir().ends_with("engines"));
    }

    #[test]
    fn normalize_strips_trailing_separators() {
        assert_eq!(normalize_user_path("  C:\\Work\\Docs\\  "), PathBuf::from("C:\\Work\\Docs"));
        assert_eq!(normalize_user_path("/home/u/docs/"), PathBuf::from("/home/u/docs"));
    }
}
