//! `presets.ini` generation for llama-server router mode (design §3.3.2).
//! One global section plus one section per installed, loadable model with
//! absolute file paths. Regenerated before every engine start and whenever
//! the model folder changes (`GET /models?reload=1` afterwards).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::error::{CoreError, Result};
use crate::hw::{Backend, Tier};
use crate::modelstore::DiscoveredModel;
use crate::pipeline::image::VisionGeometry;
use crate::registry::{ModelEntry, ModelRole, Registry};
use crate::settings::{ModelSettings, Profile};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PresetModel {
    pub id: String,
    pub model: PathBuf,
    pub mmproj: Option<PathBuf>,
    /// Ordered `key = value` pairs (keys are llama-server flags without dashes).
    pub options: Vec<(String, String)>,
    pub load_on_startup: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct PresetFile {
    pub global: Vec<(String, String)>,
    pub models: Vec<PresetModel>,
}

/// The llama.cpp INI parser has no escaping: `;` and `#` start a comment and
/// a value ends at the line. Paths containing them cannot be expressed.
pub fn ini_value_ok(v: &str) -> bool {
    !v.contains([';', '#', '\n', '\r'])
}

pub fn ini_section_ok(v: &str) -> bool {
    !v.is_empty() && !v.contains([']', '\n', '\r'])
}

fn path_str(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

impl PresetFile {
    pub fn to_ini(&self) -> String {
        let mut out = String::new();
        out.push_str("version = 1\n");
        out.push_str("; generated by DocuLens at every engine start - edits are overwritten\n\n");
        out.push_str("[*]\n");
        for (k, v) in &self.global {
            out.push_str(&format!("{k} = {v}\n"));
        }
        for m in &self.models {
            out.push('\n');
            out.push_str(&format!("[{}]\n", m.id));
            out.push_str(&format!("model = {}\n", path_str(&m.model)));
            if let Some(mm) = &m.mmproj {
                out.push_str(&format!("mmproj = {}\n", path_str(mm)));
            }
            out.push_str(&format!("load-on-startup = {}\n", m.load_on_startup));
            for (k, v) in &m.options {
                out.push_str(&format!("{k} = {v}\n"));
            }
        }
        out
    }

    /// Writes atomically (temp + rename).
    pub fn write(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| CoreError::io(parent, e))?;
        }
        let tmp = path.with_extension("ini.tmp");
        std::fs::write(&tmp, self.to_ini()).map_err(|e| CoreError::io(&tmp, e))?;
        std::fs::rename(&tmp, path).map_err(|e| CoreError::io(path, e))?;
        Ok(())
    }
}

pub struct PresetContext<'a> {
    pub backend: Backend,
    pub tier: Tier,
    pub profile: Profile,
    pub settings: &'a ModelSettings,
    /// Model loaded at startup (`load-on-startup = true`).
    pub active_model: Option<&'a str>,
    pub debug: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct PresetBuild {
    pub file: PresetFile,
    /// Models that could not be written: (id, reason key).
    pub skipped: Vec<(String, String)>,
    /// mmproj bytes per model id — the router's memory figures exclude them (§3.3.1).
    pub mmproj_sizes: BTreeMap<String, u64>,
}

fn num(v: &serde_json::Value, key: &str) -> Option<u64> {
    v.get(key).and_then(serde_json::Value::as_u64)
}

fn fnum(v: &serde_json::Value, key: &str) -> Option<f64> {
    v.get(key).and_then(serde_json::Value::as_f64)
}

/// Context size for a profile/backend, clamped to the model maximum.
pub fn context_for(defaults: &serde_json::Value, ctx_max: u64, profile: Profile, backend: Backend) -> u64 {
    let base = num(defaults, "ctx").unwrap_or(16_384);
    let mut ctx = match profile {
        Profile::Accuracy | Profile::FinePrint => base,
        Profile::Balanced => base.min(16_384),
        Profile::Speed => base.min(8_192),
    };
    if backend == Backend::Cpu {
        ctx = ctx.min(8_192);
    }
    if ctx_max > 0 {
        ctx = ctx.min(ctx_max);
    }
    ctx.max(2_048)
}

/// Image token ceiling (design §3.4 render budget).
pub fn image_max_tokens_for(defaults: &serde_json::Value, profile: Profile, backend: Backend) -> u64 {
    let base = num(defaults, "image_max_tokens").unwrap_or(2_048);
    let by_profile = match profile {
        Profile::Accuracy => base.max(2_200),
        Profile::Balanced => base.min(2_048),
        Profile::Speed => 1_440,
        Profile::FinePrint => 3_072,
    };
    match backend {
        // CLIP flash-attention head-size issue on Vulkan (§3.3.2 note).
        Backend::Vulkan => by_profile.min(1_440),
        Backend::Cpu => 1_024,
        _ => by_profile,
    }
}

fn model_options(entry: Option<&ModelEntry>, d: &DiscoveredModel, ctx: &PresetContext) -> Vec<(String, String)> {
    let empty = serde_json::Value::Null;
    let defaults = entry.map(|e| &e.defaults).unwrap_or(&empty);
    let mut defaults = defaults.clone();
    if let Some(serde_json::Value::Object(extra)) = d.model_json.as_ref().map(|j| &j.defaults) {
        if !defaults.is_object() {
            defaults = serde_json::json!({});
        }
        if let serde_json::Value::Object(base) = &mut defaults {
            for (k, v) in extra {
                base.insert(k.clone(), v.clone());
            }
        }
    }
    let ctx_max = entry
        .map(|e| e.ctx_max)
        .or_else(|| d.primary_meta().and_then(|m| m.context_length).map(u64::from))
        .unwrap_or(0);
    let role = entry.map(|e| e.role).unwrap_or(d.role);
    let mut opts: Vec<(String, String)> = Vec::new();
    let push = |opts: &mut Vec<(String, String)>, k: &str, v: String| opts.push((k.to_string(), v));

    if role == ModelRole::Embedding {
        push(&mut opts, "embeddings", "true".into());
        let pooling = defaults.get("pooling").and_then(|v| v.as_str()).unwrap_or("cls");
        let pooling = if ["none", "mean", "cls", "last", "rank"].contains(&pooling) { pooling } else { "cls" };
        push(&mut opts, "pooling", pooling.to_string());
        let c = num(&defaults, "ctx").unwrap_or(2_048).min(if ctx_max > 0 { ctx_max } else { u64::MAX });
        push(&mut opts, "ctx-size", c.to_string());
        push(&mut opts, "batch-size", c.max(512).to_string());
        push(&mut opts, "ubatch-size", c.max(512).to_string());
        push(&mut opts, "n-gpu-layers", num(&defaults, "n_gpu_layers").unwrap_or(0).to_string());
        return opts;
    }

    push(&mut opts, "ctx-size", context_for(&defaults, ctx_max, ctx.profile, ctx.backend).to_string());
    if d.has_vision {
        // The encoder geometry bounds both ends: Gemma 4 takes 70–1,120 tokens per image, Qwen
        // drop-ins need the 1,024-token grounding floor (§3.4).
        let arch = entry.map(|e| e.arch.as_str()).or(d.architecture.as_deref()).unwrap_or("");
        let geom = VisionGeometry::for_arch(arch);
        let max_tokens = image_max_tokens_for(&defaults, ctx.profile, ctx.backend).min(u64::from(geom.max_tokens));
        let min_tokens =
            num(&defaults, "image_min_tokens").unwrap_or(u64::from(geom.default_min_tokens)).min(max_tokens);
        push(&mut opts, "image-min-tokens", min_tokens.to_string());
        push(&mut opts, "image-max-tokens", max_tokens.to_string());
    }
    let two_slots =
        ctx.backend != Backend::Cpu && matches!(ctx.tier, Tier::Vram12gb | Tier::Vram16gb | Tier::Vram24gbPlus);
    if two_slots {
        push(&mut opts, "parallel", "2".into());
        push(&mut opts, "kv-unified", "true".into());
    } else {
        push(&mut opts, "parallel", "1".into());
    }
    if let Some(t) = fnum(&defaults, "temperature") {
        push(&mut opts, "temp", trim_float(t));
    }
    if let Some(k) = num(&defaults, "top_k") {
        push(&mut opts, "top-k", k.to_string());
    }
    if let Some(p) = fnum(&defaults, "top_p") {
        push(&mut opts, "top-p", trim_float(p));
    }
    let thinking = defaults.get("thinking").and_then(|v| v.as_bool()).unwrap_or(false);
    if !thinking {
        // `--reasoning off` disables thinking in the chat template (llama.cpp ≥ b12000);
        // the budget guards older templates that ignore the switch.
        push(&mut opts, "reasoning", "off".into());
        push(&mut opts, "reasoning-budget", "0".into());
    }
    if ctx.backend == Backend::Cpu {
        push(&mut opts, "n-gpu-layers", "0".into());
    } else if ctx.settings.vision_on_cpu && d.has_vision {
        // "audit mode": ViT on the CPU (CUDA FA vision drift work-around, §3.3.2)
        push(&mut opts, "mmproj-offload", "false".into());
    }
    opts
}

fn trim_float(v: f64) -> String {
    let s = format!("{v:.3}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s.is_empty() {
        "0".into()
    } else {
        s.to_string()
    }
}

/// Global `[*]` section.
pub fn global_options(ctx: &PresetContext) -> Vec<(String, String)> {
    let mut g: Vec<(String, String)> = vec![
        ("flash-attn".into(), if ctx.backend == Backend::Cpu { "auto".into() } else { "on".into() }),
        ("cache-type-k".into(), "q8_0".into()),
        ("cache-type-v".into(), "q8_0".into()),
        // VLMs must fail loudly instead of silently offloading to the CPU (§3.3.2)
        ("fit".into(), "off".into()),
        ("n-gpu-layers".into(), if ctx.backend == Backend::Cpu { "0".into() } else { "all".into() }),
        ("batch-size".into(), "2048".into()),
        ("ubatch-size".into(), "512".into()),
        ("jinja".into(), "true".into()),
        ("metrics".into(), "true".into()),
    ];
    if !ctx.debug {
        // `/slots` exposes prompts (PII) — debug builds only (§3.3.1)
        g.push(("slots".into(), "false".into()));
    }
    g
}

/// Builds the preset file from the scan results. Only models whose files are
/// complete and whose architecture llama.cpp can load are written.
pub fn build_presets(registry: &Registry, discovered: &[DiscoveredModel], ctx: &PresetContext) -> PresetBuild {
    let mut build =
        PresetBuild { file: PresetFile { global: global_options(ctx), models: Vec::new() }, ..Default::default() };
    let mut seen = std::collections::BTreeSet::new();
    for d in discovered {
        let id = d.id.clone();
        if !d.health.is_ready() {
            build.skipped.push((id, "not_ready".into()));
            continue;
        }
        let Some(weights) = d.weights_path() else {
            build.skipped.push((id, "no_weights".into()));
            continue;
        };
        let path_ok = |p: &Path| p.to_str().is_some_and(ini_value_ok);
        if !ini_section_ok(&id) || !path_ok(weights) || d.mmproj_path().is_some_and(|p| !path_ok(p)) {
            build.skipped.push((id, "path_not_representable".into()));
            continue;
        }
        if !seen.insert(id.clone()) {
            build.skipped.push((id, "duplicate_id".into()));
            continue;
        }
        let entry = registry.get(&id);
        // Every value comes from registry defaults or `model.json`; the INI has no escaping.
        let options: Vec<(String, String)> =
            model_options(entry, d, ctx).into_iter().filter(|(_, v)| ini_value_ok(v)).collect();
        if let Some(mm) = &d.mmproj {
            build.mmproj_sizes.insert(id.clone(), mm.size);
        }
        build.file.models.push(PresetModel {
            load_on_startup: ctx.active_model == Some(id.as_str()),
            id,
            model: weights.to_path_buf(),
            mmproj: d.mmproj_path().map(Path::to_path_buf),
            options,
        });
    }
    build
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gguf::{synthetic_gemma4_metadata, write_minimal_gguf, GgufValue};
    use crate::modelstore::{scan_models_dir, ScanOptions};

    fn fixture(dir: &Path) -> Vec<DiscoveredModel> {
        let q = dir.join("gemma");
        std::fs::create_dir_all(&q).unwrap();
        write_minimal_gguf(
            &q.join("gemma-4-E4B-it-Q6_K.gguf"),
            &synthetic_gemma4_metadata("Gemma 4 E4B", 18, true),
            &[("a", &[8], 0)],
        )
        .unwrap();
        write_minimal_gguf(
            &q.join("mmproj-F16.gguf"),
            &[
                ("general.architecture", GgufValue::String("clip".into())),
                ("clip.projector_type", GgufValue::String("gemma4v".into())),
                ("clip.has_vision_encoder", GgufValue::Bool(true)),
            ],
            &[("v", &[8], 1)],
        )
        .unwrap();
        let e = dir.join("embed");
        std::fs::create_dir_all(&e).unwrap();
        let mut emb = synthetic_gemma4_metadata("EmbeddingGemma 2", 7, false);
        emb[0] = ("general.architecture", GgufValue::String("gemma-embedding2".into()));
        write_minimal_gguf(&e.join("embeddinggemma-2-Q8_0.gguf"), &emb, &[("a", &[8], 0)]).unwrap();
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(60);
        for d in [&q, &e] {
            for f in std::fs::read_dir(d).unwrap().flatten() {
                std::fs::File::options().write(true).open(f.path()).unwrap().set_modified(old).unwrap();
            }
        }
        scan_models_dir(dir, &Registry::builtin(), ScanOptions::default())
    }

    #[test]
    fn generates_sections_with_absolute_paths_and_profile_rules() {
        let tmp = tempfile::tempdir().unwrap();
        let found = fixture(tmp.path());
        assert_eq!(found.len(), 2);
        let settings = ModelSettings::default();
        let ctx = PresetContext {
            backend: Backend::Cu121,
            tier: Tier::Vram8gb,
            profile: Profile::Accuracy,
            settings: &settings,
            active_model: Some("gemma4-e4b-q6k"),
            debug: false,
        };
        let b = build_presets(&Registry::builtin(), &found, &ctx);
        assert!(b.skipped.is_empty(), "{:?}", b.skipped);
        let ini = b.file.to_ini();
        assert!(ini.starts_with("version = 1\n"));
        assert!(ini.contains("[*]\nflash-attn = on\n"));
        assert!(!ini.contains("[*]\nflash-attn = on\n") || !ini.split("[gemma4").next().unwrap().contains("image-min-tokens"), "the image floor is per model, not global");
        assert!(ini.contains("slots = false"));
        assert!(ini.contains("[gemma4-e4b-q6k]\n"));
        assert!(ini.contains(&format!("model = {}\n", tmp.path().join("gemma").join("gemma-4-E4B-it-Q6_K.gguf").display())));
        assert!(ini.contains("mmproj = "));
        // accuracy profile asks for 2,200 image tokens; Gemma 4's encoder caps at 1,120 and floors at 512
        assert!(ini.contains("load-on-startup = true\nctx-size = 32768\nimage-min-tokens = 512\nimage-max-tokens = 1120\nparallel = 1\ntemp = 0.1\ntop-k = 64\ntop-p = 0.95\nreasoning = off\nreasoning-budget = 0\n"), "{ini}");
        assert!(ini.contains("[embed-gemma2-q8]\n"));
        assert!(ini.contains("embeddings = true\npooling = mean\nctx-size = 2048\n"));
        assert_eq!(b.mmproj_sizes.len(), 1);
        // 12 GB → two slots; speed profile → 8K ctx, 1440 image tokens; vulkan caps image tokens
        let ctx = PresetContext {
            backend: Backend::Vulkan,
            tier: Tier::Vram12gb,
            profile: Profile::Speed,
            settings: &settings,
            active_model: None,
            debug: true,
        };
        let ini = build_presets(&Registry::builtin(), &found, &ctx).file.to_ini();
        assert!(ini.contains("ctx-size = 8192\nimage-min-tokens = 512\nimage-max-tokens = 1120\nparallel = 2\nkv-unified = true\n"), "{ini}");
        assert!(ini.contains("load-on-startup = false"));
        assert!(!ini.contains("slots = false"));
        // cpu backend → no GPU layers anywhere
        let ctx = PresetContext {
            backend: Backend::Cpu,
            tier: Tier::CpuOnly,
            profile: Profile::Accuracy,
            settings: &settings,
            active_model: None,
            debug: false,
        };
        let ini = build_presets(&Registry::builtin(), &found, &ctx).file.to_ini();
        assert!(ini.contains("n-gpu-layers = 0\nbatch-size"));
        assert!(ini.contains("image-min-tokens = 512\nimage-max-tokens = 1024\n"), "{ini}");
        assert!(ini.contains("flash-attn = auto"));
    }

    #[test]
    fn qwen_drop_in_keeps_its_grounding_floor_and_wider_ceiling() {
        let defaults = serde_json::json!({ "image_max_tokens": 2048 });
        // the shared helper is geometry-agnostic; model_options clamps with the arch
        assert_eq!(image_max_tokens_for(&defaults, Profile::Accuracy, Backend::Cu129), 2_200);
        assert_eq!(image_max_tokens_for(&defaults, Profile::FinePrint, Backend::Cu129), 3_072);
        assert_eq!(VisionGeometry::for_arch("qwen35").default_min_tokens, 1_024);
        assert_eq!(VisionGeometry::for_arch("gemma4").max_tokens, 1_120);
    }

    #[test]
    fn unrepresentable_paths_are_skipped() {
        assert!(ini_value_ok("C:\\Work\\Docs\\.doculens\\models\\q\\x.gguf"));
        assert!(!ini_value_ok("C:\\Work\\#docs\\x.gguf"));
        assert!(!ini_value_ok("a;b"));
        assert!(ini_section_ok("gemma4-e4b-q6k"));
        assert!(!ini_section_ok("a]b"));
        assert_eq!(trim_float(0.1), "0.1");
        assert_eq!(trim_float(1.0), "1");
        assert_eq!(context_for(&serde_json::json!({"ctx": 32768}), 262_144, Profile::Balanced, Backend::Cu129), 16_384);
        assert_eq!(context_for(&serde_json::json!({"ctx": 32768}), 4_096, Profile::Accuracy, Backend::Cu129), 4_096);
    }
}
