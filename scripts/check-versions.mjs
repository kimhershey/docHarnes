#!/usr/bin/env node
// Version consistency gate (CLAUDE.md "One version per branch"). Run: npm run versions:check
//
// Every place that records the application version must agree with src-tauri/tauri.conf.json — the value the
// release workflows turn into the installer name and the Release tag v<version>:
//
//   Cargo.toml                 [workspace.package] version (member crates use `version.workspace = true`)
//   Cargo.lock                 the workspace members' [[package]] entries — a stale lock fails
//                              `cargo metadata --locked` (scripts/gen-notices.mjs, the CI notices job)
//   package.json               version
//   package-lock.json          version and packages[""].version
//   src/lib/mock-backend.ts    app_version / last_opened_app_version / the app_info version (browser preview, e2e)
//   sbom.cdx.json              metadata.component.version (regenerated by `npm run notices`)
//
// On a branch named release/<major.minor.patch> the version must also be the one in the branch name. The branch
// comes from --branch <name> or, on GitHub Actions, from GITHUB_REF_NAME (the branch a push or a manual dispatch
// runs on); other branch names are not checked.
//
// Exit code 1 on any mismatch, on a version string that can no longer be found (a check that reads nothing is
// not a pass) and on an unreadable file. No dependencies: runs right after checkout, before `npm ci`.
import { readFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel) => readFileSync(path.join(ROOT, rel), "utf8");
const readJson = (rel) => JSON.parse(read(rel));

/**
 * `[table]` → { key: raw value } for the flat `key = value` lines of a TOML file (enough for Cargo manifests).
 * Array tables (`[[bin]]`) are kept apart under their bracketed name so their keys never land in `[package]`.
 */
function tomlTables(text) {
  const tables = new Map();
  let current = "";
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\s+#.*$/, "").trim();
    const header = /^(\[\[?)([^\][]+)\]\]?$/.exec(line);
    if (header) {
      current = header[1] === "[[" ? `[[${header[2].trim()}]]` : header[2].trim();
      continue;
    }
    const kv = /^([A-Za-z0-9_.-]+)\s*=\s*(.+)$/.exec(line);
    if (!kv) continue;
    if (!tables.has(current)) tables.set(current, {});
    tables.get(current)[kv[1]] = kv[2].trim();
  }
  return tables;
}

const unquote = (v) => (/^"([^"]*)"/.exec(v ?? "") ?? [])[1] ?? null;

/** name → version of the path packages (no `source`) in Cargo.lock. */
function lockedWorkspacePackages(text) {
  const out = new Map();
  for (const block of text.split(/\r?\n\[\[package\]\]\r?\n/).slice(1)) {
    const name = /^name = "([^"]+)"/m.exec(block)?.[1];
    const version = /^version = "([^"]+)"/m.exec(block)?.[1];
    if (name && version && !/^source = /m.test(block)) out.set(name, version);
  }
  return out;
}

/** Collects { where, version } rows; a version of null means "not found". */
function collect() {
  const rows = [];
  const add = (where, version) => rows.push({ where, version: version ?? null });

  add("src-tauri/tauri.conf.json  version", readJson("src-tauri/tauri.conf.json").version);

  const cargo = tomlTables(read("Cargo.toml"));
  const workspaceVersion = unquote(cargo.get("workspace.package")?.version);
  add("Cargo.toml  [workspace.package] version", workspaceVersion);

  const members = [...(cargo.get("workspace")?.members ?? "").matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  if (!members.length) add("Cargo.toml  [workspace] members", null);
  const locked = lockedWorkspacePackages(read("Cargo.lock"));
  for (const member of members) {
    const manifest = `${member}/Cargo.toml`;
    const pkg = tomlTables(read(manifest)).get("package") ?? {};
    const name = unquote(pkg.name);
    // `version.workspace = true` inherits the workspace version; a literal version must agree on its own.
    const inherits = pkg["version.workspace"] === "true" || /^\{\s*workspace\s*=\s*true\s*\}$/.test(pkg.version ?? "");
    if (!inherits) add(`${manifest}  [package] version`, unquote(pkg.version));
    add(`Cargo.lock  ${name ?? member}`, name ? locked.get(name) : null);
  }

  add("package.json  version", readJson("package.json").version);
  const lock = readJson("package-lock.json");
  add("package-lock.json  version", lock.version);
  add('package-lock.json  packages[""].version', lock.packages?.[""]?.version);

  const mock = read("src/lib/mock-backend.ts");
  const manifestVersions = [...mock.matchAll(/\b((?:last_opened_)?app_version):\s*"([^"]*)"/g)];
  if (!manifestVersions.length) add("src/lib/mock-backend.ts  app_version", null);
  for (const m of manifestVersions) add(`src/lib/mock-backend.ts  ${m[1]}`, m[2]);
  const appInfo = /name:\s*"DocuLens",\s*version:\s*"([^"]*)"/.exec(mock);
  add("src/lib/mock-backend.ts  app_info version", appInfo?.[1]);

  add("sbom.cdx.json  metadata.component.version", readJson("sbom.cdx.json").metadata?.component?.version);
  return rows;
}

function branchArg(argv) {
  const i = argv.indexOf("--branch");
  if (i >= 0) return argv[i + 1] ?? "";
  return process.env.GITHUB_REF_NAME ?? "";
}

let rows;
try {
  rows = collect();
} catch (e) {
  console.error(`versions: ${e.message}`);
  process.exit(1);
}
const expected = rows[0].version;
const width = Math.max(...rows.map((r) => r.where.length));
let bad = 0;
for (const r of rows) {
  const ok = r.version !== null && r.version === expected;
  if (!ok) bad++;
  console.log(`${ok ? "  ok " : "  BAD"}  ${r.where.padEnd(width)}  ${r.version ?? "(not found)"}`);
}

const branch = branchArg(process.argv.slice(2));
const release = /^release\/(\d+\.\d+\.\d+)$/.exec(branch);
if (release) {
  const ok = release[1] === expected;
  if (!ok) bad++;
  console.log(`${ok ? "  ok " : "  BAD"}  ${`branch ${branch}`.padEnd(width)}  ${release[1]}`);
}

if (bad || !expected) {
  console.error(
    `\nversions disagree: ${bad} of ${rows.length + (release ? 1 : 0)} entries differ from src-tauri/tauri.conf.json (${expected ?? "not found"}).` +
      "\nBump every place together (CLAUDE.md, Working method 6): Cargo.toml + Cargo.lock (`cargo update -w --offline`)," +
      "\npackage.json + package-lock.json, src-tauri/tauri.conf.json, the mock backend's version strings, then `npm run notices`.",
  );
  process.exit(1);
}
console.log(`\nversion ${expected}: ${rows.length} entries agree${release ? ` and match branch ${branch}` : ""}`);
